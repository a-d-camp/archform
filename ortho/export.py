"""Export a design as the browser builder's shape (builder/src/shape.js).

The builder evaluates the same bicubic B-spline and outline, then lets you adjust the arch on top.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from .geometry import Design


def shape_record(design: Design) -> dict:
    o, S = design.outline, design.surface
    L = o.length
    xs = np.linspace(o.x0, o.x1, 241)
    ymax, ymin = o.edges(xs)
    # where the arch peaks along the inner edge (for centring the arch adjustments)
    xx = np.linspace(o.x0, o.x1, 400)
    inner = design.top(xx, o.edges(xx)[0])
    peak_x = float(xx[np.argmax(inner)])
    rec = {
        "thickness": design.thickness,
        "length": round(L, 3),
        "edges": {"x": (xs - o.x0).round(3).tolist(), "ymax": ymax.round(3).tolist(), "ymin": ymin.round(3).tolist()},
        "spline": {"ts": S.ts.round(6).tolist(), "tv": S.tv.round(6).tolist(),
                   "C": np.asarray(design.heights).round(3).tolist()},
        "arch": {"peak_x": round(peak_x - o.x0, 2), "peak_s": round((peak_x - o.x0) / L, 4)},
    }
    if design.opening is not None:
        cx, cy = design.opening.center
        rec["opening"] = {"center": [round(cx - o.x0, 2), round(cy, 2)], "size": list(design.opening.size)}
        if design.opening.fourier is not None:
            rec["opening"]["fourier"] = [round(float(c), 3) for c in design.opening.fourier]
    return rec


def write_shape(record: dict, path) -> None:
    body = json.dumps(record, separators=(",", ":"))
    Path(path).write_text(
        "// Generated by `uv run ortho export` from a design in designs/. Do not edit by hand.\n"
        "// The builder's shape: outline table, heel opening and B-spline surface.\n"
        "(function (root) {\n"
        f"  root.OrthoShape = {body};\n"
        "})(typeof window !== 'undefined' ? window : globalThis);\n")
